// Decoded once: Map<char, Uint8Array(GLYPH_W * GLYPH_H)>
export const FONT = new Map();
for (const [ch, spec] of Object.entries(G)) {
  const rows = spec.split('/');
  const bits = new Uint8Array(GLYPH_W * GLYPH_H);
  for (let y = 0; y < GLYPH_H; y++) {
    const row = rows[y] || '';
    for (let x = 0; x < GLYPH_W; x++) bits[y * GLYPH_W + x] = row[x] === '#' ? 1 : 0;
  }
  FONT.set(ch, bits);
}

export function glyph(ch) {
  return FONT.get(ch) || FONT.get('?');
}
